# Завдання 1. Розрахунок доходу за вкладом (у місяцях)

print("— Вкладник: «Хочу розрахувати свій прибуток за вкладом, якщо відомі сума, річна ставка та термін у місяцях.»")
print("— Розробник: «Обчислимо чистий дохід за пропорцією терміну в місяцях.»\n")

# 1. Введення даних
deposit = float(input("Введіть суму депозиту P (грн): "))
rate = float(input("Введіть річну ставку r (%): "))
months = float(input("Введіть термін вкладу m (місяців): "))

# 2. Обчислення доходу
income = deposit * rate / 100 * months / 12

# 3. Виведення результатів
print("\n--- Результати обчислень ---")
print(f"Величина доходу (Income): {income:.2f} грн")




# Завдання 2. Прості відсотки за депозитом

print("— Вкладник: «Якщо я покладу 50 000 грн під 15% річних на 180 днів, скільки прибутку отримаю?»")
print("— Розробник: «Я напишу програму для розрахунку простих відсотків за формулою банківського дня.»\n")

# 1. Введення даних
deposit_amount = float(input("Введіть суму депозиту P (грн): "))
rate = float(input("Введіть річну відсоткову ставку r (%): "))
days = float(input("Введіть термін вкладу t (днів): "))

# 2. Обчислення відсотків
interest = deposit_amount * rate / 100 * days / 360

# 3. Обчислення підсумкової суми
total = deposit_amount + interest

# 4. Виведення результатів
print("\n--- Результати обчислень ---")
print(f"Сума прибутку (I): {interest:.2f} грн")
print(f"Підсумкова сума (S): {total:.2f} грн")